// Helper : normalise un nom de TA en niveau de zone (1/2/3) selon le cahier des charges
window.taToZoneLevel = function(taName) {
  const m = String(taName).match(/(\d+)/);
  if (!m) return null;
  const n = parseInt(m[1], 10);
  if (n === 0) return "1";    // TA00 = cœur, traité comme niveau 1
  if (n <= 1) return "1";
  if (n <= 2) return "2";
  return "3";
};
